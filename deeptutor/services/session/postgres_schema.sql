-- Dr. Chen AI PostgreSQL schema (initial draft)
-- Not yet connected to the application.

CREATE TABLE IF NOT EXISTS drchen_sessions (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT 'New conversation',
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    compressed_summary TEXT DEFAULT '',
    summary_up_to_msg_id BIGINT DEFAULT 0,
    preferences_json TEXT DEFAULT '{}',
    deleted_at DOUBLE PRECISION
);

CREATE INDEX IF NOT EXISTS idx_drchen_sessions_user_updated
    ON drchen_sessions(user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS drchen_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL
        REFERENCES drchen_sessions(id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    content TEXT NOT NULL DEFAULT '',
    capability TEXT DEFAULT '',
    events_json TEXT DEFAULT '',
    attachments_json TEXT DEFAULT '',
    metadata_json TEXT DEFAULT '{}',
    created_at DOUBLE PRECISION NOT NULL,
    parent_message_id BIGINT
        REFERENCES drchen_messages(id)
);

CREATE INDEX IF NOT EXISTS idx_drchen_messages_session_created
    ON drchen_messages(session_id, created_at, id);
