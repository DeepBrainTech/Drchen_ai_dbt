-- Dr. Chen AI PostgreSQL schema (initial draft)
-- Not yet connected to the application.

CREATE TABLE IF NOT EXISTS drchen_sessions (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT 'New conversation',
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    compressed_summary TEXT DEFAULT '',
    summary_up_to_msg_id BIGINT DEFAULT 0,
    preferences_json TEXT DEFAULT '{}',
    deleted_at DOUBLE PRECISION
);

CREATE INDEX IF NOT EXISTS idx_drchen_sessions_user_updated
    ON drchen_sessions(user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS drchen_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL
        REFERENCES drchen_sessions(id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    content TEXT NOT NULL DEFAULT '',
    capability TEXT DEFAULT '',
    events_json TEXT DEFAULT '',
    attachments_json TEXT DEFAULT '',
    metadata_json TEXT DEFAULT '{}',
    created_at DOUBLE PRECISION NOT NULL,
    parent_message_id BIGINT
        REFERENCES drchen_messages(id)
);

CREATE INDEX IF NOT EXISTS idx_drchen_messages_session_created
    ON drchen_messages(session_id, created_at, id);

    -- Track AI response turns for each conversation.
CREATE TABLE IF NOT EXISTS drchen_turns (
    id TEXT PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES drchen_sessions(id) ON DELETE CASCADE,
    capability TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'running',
    error TEXT NOT NULL DEFAULT '',
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    finished_at DOUBLE PRECISION,
    owner_id TEXT NOT NULL DEFAULT '',
    fencing_token BIGINT NOT NULL DEFAULT 0,
    state_version INTEGER NOT NULL DEFAULT 1,
    failure_code TEXT NOT NULL DEFAULT '',
    retryable BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT drchen_turn_status_check
        CHECK (status IN (
            'queued', 'running', 'waiting_input',
            'completed', 'failed', 'cancelled'
        ))
);

-- Prevent simultaneous active AI turns in one conversation.
CREATE UNIQUE INDEX IF NOT EXISTS drchen_one_active_turn
ON drchen_turns (session_id)
WHERE status IN ('queued', 'running', 'waiting_input');


-- Add the assistant message reference to AI turns.
ALTER TABLE drchen_turns
ADD COLUMN IF NOT EXISTS assistant_message_id BIGINT;

-- Track client submissions to prevent duplicate AI requests.
CREATE TABLE IF NOT EXISTS drchen_turn_submissions (
    client_submission_id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL DEFAULT '',
    request_digest TEXT NOT NULL,
    session_id TEXT NOT NULL
        REFERENCES drchen_sessions(id) ON DELETE CASCADE,
    turn_id TEXT
        REFERENCES drchen_turns(id) ON DELETE SET NULL
);

-- Store AI turn events in sequence.
CREATE TABLE IF NOT EXISTS drchen_turn_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turn_id TEXT NOT NULL
        REFERENCES drchen_turns(id) ON DELETE CASCADE,
    seq BIGINT NOT NULL,
    type TEXT NOT NULL,
    source TEXT DEFAULT '',
    stage TEXT DEFAULT '',
    content TEXT DEFAULT '',
    metadata_json TEXT DEFAULT '',
    timestamp DOUBLE PRECISION NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    UNIQUE (turn_id, seq)
);

CREATE INDEX IF NOT EXISTS idx_drchen_turn_events_turn_seq
ON drchen_turn_events(turn_id, seq);

CREATE INDEX IF NOT EXISTS idx_drchen_turns_session_updated
ON drchen_turns(session_id, updated_at DESC);
