"""Image- and video-generation chat tools.

Thin BaseTool front-ends over the ``imagegen`` / ``videogen`` services. Each
call generates media via the active catalog model, writes the bytes into the
turn's content workspace, and returns the files as artifacts — reusing the exact
same ``collect_public_artifacts`` convention as the unified exec tool. Saving and
presentation are intentionally separate: the model must pass each returned
workspace-relative path to ``workspace_present`` before linking it.

Mounting & gating (set by the chat pipeline, not here):

* User-toggleable in /settings/tools, so per-user ``enabled_tools`` grants apply.
* Only mounted for a turn when an active model is configured for the service.
* ``_workspace_dir`` is injected server-side by ``_augment_tool_kwargs``; the
  LLM only supplies ``prompt`` (+ optional knobs).
"""

from __future__ import annotations

import logging
from pathlib import Path
import re
from typing import TYPE_CHECKING, Any
import uuid

from deeptutor.core.tool_protocol import BaseTool, ToolDefinition, ToolParameter, ToolResult
from deeptutor.tools.prompting import load_prompt_hints

if TYPE_CHECKING:
    from deeptutor.services.sandbox.artifacts import SandboxArtifact

logger = logging.getLogger(__name__)

_EXT_BY_CONTENT_TYPE = {
    "image/png": "png",
    "image/jpeg": "jpg",
    "image/webp": "webp",
    "image/gif": "gif",
    "video/mp4": "mp4",
    "video/webm": "webm",
    "video/quicktime": "mov",
}


def _slug(prompt: str, fallback: str) -> str:
    """Short ascii filename stem from a prompt; ``fallback`` when none survives."""
    words = re.findall(r"[A-Za-z0-9]+", prompt.lower())
    stem = "_".join(words[:6])[:40]
    return stem or fallback


def _ext(content_type: str, default: str) -> str:
    return _EXT_BY_CONTENT_TYPE.get((content_type or "").split(";")[0].strip(), default)


def _run_dir(injected: str | None, kind: str, *, workspace_id: str = "") -> tuple[Path, str]:
    """A fresh per-call dir under the public outputs root.

    A real chat turn injects both the physical output directory and the opaque
    workspace id. Direct SDK/registry calls do not, so create a normal runtime
    workspace context for them instead of reviving the pre-workspace
    ``data/user/workspace/chat/...`` layout. This keeps pip, source, and Docker
    calls on the same ``<selected workspace>/outputs/...`` contract.

    Per-call subdirs keep ``collect_public_artifacts`` scoped to this call's
    files only.
    """
    if injected and workspace_id:
        base = Path(injected)
    else:
        from deeptutor.services.workspace import get_content_workspace_service

        runtime = get_content_workspace_service().create_runtime_context(
            capability="chat",
            session_id="direct",
            turn_id="media_gen",
        )
        base = Path(runtime.output_dir) / "media"
        workspace_id = runtime.workspace_id
    run = base / f"{kind}_{uuid.uuid4().hex[:12]}"
    run.mkdir(parents=True, exist_ok=True)
    return run, workspace_id


def _write_media(
    run_dir: Path,
    media: list[tuple[bytes, str]],
    *,
    stem: str,
    default_ext: str,
    workspace_id: str = "",
) -> list[SandboxArtifact]:
    """Write generated bytes to ``run_dir`` and return their public artifacts."""
    from deeptutor.services.sandbox.artifacts import collect_public_artifacts

    multiple = len(media) > 1
    for index, (data, content_type) in enumerate(media, start=1):
        if not data:
            continue
        suffix = f"_{index}" if multiple else ""
        filename = f"{stem}{suffix}.{_ext(content_type, default_ext)}"
        (run_dir / filename).write_bytes(data)
    return collect_public_artifacts(str(run_dir), workspace_id=workspace_id)


def _artifact_result(
    artifacts: list[SandboxArtifact], *, empty_message: str, workspace_id: str = "", **meta: Any
) -> ToolResult:
    from deeptutor.services.sandbox.artifacts import render_artifacts_for_tool

    if not artifacts:
        return ToolResult(content=empty_message, success=False)
    rows = [artifact.to_dict() for artifact in artifacts]
    return ToolResult(
        content=render_artifacts_for_tool(artifacts, already_presented=not bool(workspace_id)),
        sources=(
            []
            if workspace_id
            else [
                {
                    "type": "artifact",
                    "filename": row["filename"],
                    "url": row["url"],
                    "path": row["path"],
                    "mime_type": row["mime_type"],
                    "size_bytes": row["size_bytes"],
                }
                for row in rows
            ]
        ),
        metadata={"artifacts": rows, "workspace_items": [], **meta},
    )


class ImagegenTool(BaseTool):
    """Generate images from a text prompt via the configured imagegen model."""

    def get_prompt_hints(self, language: str = "en"):
        return load_prompt_hints(self.name, language=language)

    def get_definition(self) -> ToolDefinition:
        return ToolDefinition(
            name="imagegen",
            description=(
                "Generate one or more images from a text description using the "
                "configured image-generation model. Write a vivid, self-contained "
                "`prompt` describing the subject, style, and composition. Generated "
                "images are saved under the active workspace's outputs/. After "
                "generation, call workspace_present with each returned exact path "
                "before linking it in Markdown; never invent a path or paste a "
                "provider URL."
            ),
            parameters=[
                ToolParameter(
                    name="prompt",
                    type="string",
                    description="A detailed description of the image to generate.",
                ),
                ToolParameter(
                    name="size",
                    type="string",
                    description="Optional WxH like '1024x1024' or '1792x1024'. Omit for the default.",
                    required=False,
                ),
                ToolParameter(
                    name="n",
                    type="integer",
                    description="How many images to generate (1-4). Default 1.",
                    required=False,
                    default=1,
                ),
            ],
        )

    async def execute(self, **kwargs: Any) -> ToolResult:
        from deeptutor.services.imagegen import GenerationProviderError, generate_image

        prompt = str(kwargs.get("prompt") or "").strip()
        if not prompt:
            return ToolResult(content="imagegen requires a non-empty 'prompt'.", success=False)
        size = str(kwargs.get("size") or "").strip() or None
        try:
            count = int(kwargs.get("n") or 1)
        except (TypeError, ValueError):
            count = 1
        count = max(1, min(count, 4))

        try:
            images = await generate_image(prompt, size=size, n=count)
        except ValueError as exc:  # not configured
            return ToolResult(content=str(exc), success=False)
        except GenerationProviderError as exc:
            logger.warning("imagegen failed: %s", exc)
            return ToolResult(content=f"Image generation failed: {exc}", success=False)

        workspace_id = str(kwargs.get("_workspace_id") or "")
        run_dir, workspace_id = _run_dir(
            kwargs.get("_workspace_dir"), "imagegen", workspace_id=workspace_id
        )
        artifacts = _write_media(
            run_dir,
            images,
            stem=_slug(prompt, "image"),
            default_ext="png",
            workspace_id=workspace_id,
        )
        return _artifact_result(
            artifacts,
            empty_message="Image generation produced no saved files.",
            workspace_id=workspace_id,
            prompt=prompt,
            count=len(artifacts),
            kind="image",
        )


class VideogenTool(BaseTool):
    """Generate a video from a text prompt via the configured videogen model."""

    def get_prompt_hints(self, language: str = "en"):
        return load_prompt_hints(self.name, language=language)

    def get_definition(self) -> ToolDefinition:
        return ToolDefinition(
            name="videogen",
            description=(
                "Generate a short video from a text description using the configured "
                "video-generation model. Write a vivid, self-contained `prompt` "
                "describing the scene, motion, and style. Rendering is slow (it may "
                "take a minute or more). The video is saved under the active "
                "workspace's outputs/. After generation, call workspace_present with "
                "the returned exact path before linking it in Markdown; never invent "
                "a path or paste a provider URL."
            ),
            parameters=[
                ToolParameter(
                    name="prompt",
                    type="string",
                    description="A detailed description of the video to generate.",
                ),
                ToolParameter(
                    name="aspect_ratio",
                    type="string",
                    description="Optional aspect ratio like '16:9' or '9:16'. Omit for the default.",
                    required=False,
                ),
                ToolParameter(
                    name="duration",
                    type="string",
                    description="Optional duration in seconds (e.g. '5'). Omit for the default.",
                    required=False,
                ),
            ],
        )

    async def execute(self, **kwargs: Any) -> ToolResult:
        from deeptutor.services.videogen import GenerationProviderError, generate_video

        prompt = str(kwargs.get("prompt") or "").strip()
        if not prompt:
            return ToolResult(content="videogen requires a non-empty 'prompt'.", success=False)
        aspect_ratio = str(kwargs.get("aspect_ratio") or "").strip() or None
        duration = str(kwargs.get("duration") or "").strip() or None

        event_sink = kwargs.get("event_sink")

        async def _progress(message: str) -> None:
            if event_sink is None:
                return
            try:
                await event_sink("tool_log", message)
            except Exception:  # progress is best-effort; never fail the render
                logger.debug("videogen progress emit failed", exc_info=True)

        try:
            video, content_type = await generate_video(
                prompt,
                aspect_ratio=aspect_ratio,
                duration=duration,
                progress=_progress,
            )
        except ValueError as exc:  # not configured
            return ToolResult(content=str(exc), success=False)
        except GenerationProviderError as exc:
            logger.warning("videogen failed: %s", exc)
            return ToolResult(content=f"Video generation failed: {exc}", success=False)

        workspace_id = str(kwargs.get("_workspace_id") or "")
        run_dir, workspace_id = _run_dir(
            kwargs.get("_workspace_dir"), "videogen", workspace_id=workspace_id
        )
        artifacts = _write_media(
            run_dir,
            [(video, content_type)],
            stem=_slug(prompt, "video"),
            default_ext="mp4",
            workspace_id=workspace_id,
        )
        return _artifact_result(
            artifacts,
            empty_message="Video generation produced no saved file.",
            workspace_id=workspace_id,
            prompt=prompt,
            kind="video",
        )




class AudiogenTool(BaseTool):
    """Generate playable MP3 narration and educational podcasts."""

    def get_definition(self) -> ToolDefinition:
        return ToolDefinition(
            name="audiogen",
            description=(
                "Generate real MP3 audio for narration, podcasts, lessons "
                "and skill demonstrations. Use this tool instead of Python "
                "libraries such as gTTS, pydub or pyttsx3. "
                "Provide dialogue as lines beginning with Teacher: or Student:. "
                "After generation, call workspace_present with the returned path."
            ),
            parameters=[
                ToolParameter(
                    name="prompt",
                    type="string",
                    description="Complete narration or teacher-student dialogue.",
                ),
            ],
        )

    async def execute(self, **kwargs: Any) -> ToolResult:
        import asyncio
        import os

        from deeptutor.services.voice import synthesize_speech
        from deeptutor.services.config.provider_runtime import resolve_tts_runtime_config
        from deeptutor.services.voice.options import voice_model_options
        from deeptutor.capabilities.audio_overview.pipeline import _render_audio
        from deeptutor.services.sandbox.artifacts import collect_public_artifacts

        script = str(kwargs.get("prompt") or "").strip()

        if not script or len(script) > 12000:
            return ToolResult(
                content="Provide a script between 1 and 12000 characters.",
                success=False,
            )

        workspace_id = str(kwargs.get("_workspace_id") or "")
        workspace_dir = kwargs.get("_workspace_dir")

        if not workspace_id or not workspace_dir:
            return ToolResult(
                content="No active workspace is available for audio generation.",
                success=False,
            )

        try:
            catalog = None

            try:
                tts = resolve_tts_runtime_config()
            except ValueError as exc:
                if "No active TTS model" not in str(exc):
                    raise

                key = os.getenv("DRCHEN_LLM_API_KEY", "").strip()
                if not key:
                    return ToolResult(
                        content="Audio provider is not configured.",
                        success=False,
                    )

                catalog = {
                    "services": {
                        "tts": {
                            "active_profile_id": "audio-fallback",
                            "active_model_id": "audio-fallback-model",
                            "profiles": [{
                                "id": "audio-fallback",
                                "name": "DrChenAI Audio",
                                "binding": "openai",
                                "base_url": "https://api.openai.com/v1",
                                "api_key": key,
                                "models": [{
                                    "id": "audio-fallback-model",
                                    "name": "tts-1",
                                    "model": "tts-1",
                                    "voice": "alloy",
                                }],
                            }],
                        }
                    }
                }

                tts = resolve_tts_runtime_config(catalog=catalog)

            choices = voice_model_options(
                tts.provider_name, "tts", tts.model
            ).get("voices", [])

            if not choices and tts.provider_name == "openai" and tts.model == "tts-1":
                choices = [{"id": "alloy"}, {"id": "nova"}]

            teacher_voice = tts.voice
            student_voice = next(
                (str(v["id"]) for v in choices if v.get("id") != teacher_voice),
                None,
            )

            segments = []
            current_speaker = "teacher"
            for line in script.splitlines():
                line = line.strip()
                if not line:
                    continue

                match = re.match(
                    r"^(Teacher|Student|Host|Expert):\s*(.*)$",
                    line,
                    re.IGNORECASE,
                )

                if match:
                    current_speaker = (
                        "student" if match.group(1).lower()
                        in {"student", "expert"} else "teacher"
                    )
                    line = match.group(2).strip()

                if line:
                    segments.append((current_speaker, line))

            if not segments or len(segments) > 40:
                return ToolResult(
                    content="Provide between 1 and 40 dialogue segments.",
                    success=False,
                )

            if any(len(text) > 4000 for _, text in segments):
                return ToolResult(
                    content="Keep each dialogue segment below 4000 characters.",
                    success=False,
                )

            if any(role == "student" for role, _ in segments) and not student_voice:
                return ToolResult(
                    content="The audio provider does not offer a second voice.",
                    success=False,
                )

            audio_parts = []

            for role, text in segments:
                voice = student_voice if role == "student" else teacher_voice
                audio, content_type = await synthesize_speech(
                    text,
                    voice=voice,
                    response_format="mp3",
                    catalog=catalog,
                )
                audio_parts.append((audio, content_type))

            run_dir, workspace_id = _run_dir(
                workspace_dir, "audiogen", workspace_id=workspace_id
            )

            await asyncio.to_thread(
                _render_audio, audio_parts, run_dir, "drchenai-podcast"
            )

            artifacts = collect_public_artifacts(
                str(run_dir), workspace_id=workspace_id
            )

            return _artifact_result(
                artifacts,
                empty_message="Audio generation produced no saved files.",
                workspace_id=workspace_id,
                kind="audio",
            )

        except Exception as exc:
            logger.warning("Audio generation failed: %s", type(exc).__name__)
            return ToolResult(
                content="Audio generation failed. Please try again.",
                success=False,
            )

__all__ = ["ImagegenTool", "VideogenTool", "AudiogenTool"]
